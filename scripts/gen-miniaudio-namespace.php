<?php
/*
 * Generates src/vio_miniaudio_ns.h: one `#define ma_xxx vio_ma_xxx` per external
 * miniaudio symbol (MA_API functions + global variables), so php-vio's copy of
 * miniaudio links under its own names.
 *
 * Why: in the static runtimes (static-php-cli) php-vio is linked into the same
 * binary as php-glfw, which compiles its own (older) miniaudio. Under the plain
 * ma_* names the linker binds php-vio's calls to whichever copy it sees first -
 * php-vio's code then runs against an implementation whose structs have a
 * different layout than the header it was compiled with. With the prefix the
 * two copies cannot meet: php-vio always calls exactly the implementation that
 * belongs to its header, and leaving that implementation out of a build is a
 * link error (undefined vio_ma_*) instead of a silent rebind.
 *
 * Usage: php scripts/gen-miniaudio-namespace.php            (writes the header)
 *        php scripts/gen-miniaudio-namespace.php --check    (exit 1 if stale)
 *
 * Re-run after every vendor/miniaudio/miniaudio.h update; tests/core/246 fails
 * while the header is stale.
 */

/* a file-scope variable definition: `<ma_type> ma_name;` at column 0 */
const VIO_MA_GLOBAL_VAR_RE = '/^ma_\w+\s+(ma_\w+)\s*;/m';

$root   = dirname(__DIR__);
$header = $root . '/vendor/miniaudio/miniaudio.h';
$out    = $root . '/src/vio_miniaudio_ns.h';
$check  = in_array('--check', $argv, true);

$src = file_get_contents($header);
if ($src === false) {
    fwrite(STDERR, "cannot read $header\n");
    exit(2);
}
$src = str_replace("\r\n", "\n", $src);

$ver = [];
foreach (['MAJOR', 'MINOR', 'REVISION'] as $k) {
    if (!preg_match('/^#define MA_VERSION_' . $k . '\s+(\d+)/m', $src, $m)) {
        fwrite(STDERR, "MA_VERSION_$k not found\n");
        exit(2);
    }
    $ver[$k] = (int)$m[1];
}

/* External symbols of the implementation: every MA_API function (each
 * declaration names the function on the MA_API line), plus the file-scope
 * variables defined without `static` (ma_atomic_global_lock). */
preg_match_all('/^MA_API\b[^;{(]*?\b(ma_\w+)\s*\(/m', $src, $m);
preg_match_all(VIO_MA_GLOBAL_VAR_RE, $src, $v);
$names = array_values(array_unique(array_merge($m[1], $v[1])));
sort($names, SORT_STRING);

$lines   = [];
$lines[] = '/*';
$lines[] = ' * GENERATED by scripts/gen-miniaudio-namespace.php - do not edit.';
$lines[] = ' *';
$lines[] = ' * Renames every external miniaudio symbol to vio_ma_* so php-vio\'s miniaudio';
$lines[] = ' * never links against another copy in the same binary (php-glfw in the';
$lines[] = ' * static runtimes). Include src/vio_miniaudio.h, never miniaudio.h directly.';
$lines[] = ' */';
$lines[] = '';
$lines[] = '#ifndef VIO_MINIAUDIO_NS_H';
$lines[] = '#define VIO_MINIAUDIO_NS_H';
$lines[] = '';
$lines[] = '/* miniaudio version this list was generated from (checked in vio_miniaudio.h) */';
$lines[] = '#define VIO_MINIAUDIO_NS_VERSION_MAJOR    ' . $ver['MAJOR'];
$lines[] = '#define VIO_MINIAUDIO_NS_VERSION_MINOR    ' . $ver['MINOR'];
$lines[] = '#define VIO_MINIAUDIO_NS_VERSION_REVISION ' . $ver['REVISION'];
$lines[] = '#define VIO_MINIAUDIO_NS_COUNT            ' . count($names);
$lines[] = '';
foreach ($names as $n) {
    $lines[] = '#define ' . $n . ' vio_' . $n;
}
$lines[] = '';
$lines[] = '#endif /* VIO_MINIAUDIO_NS_H */';
$content = implode("\n", $lines) . "\n";

if ($check) {
    $have = @file_get_contents($out);
    $have = $have === false ? '' : str_replace("\r\n", "\n", $have);
    if ($have !== $content) {
        fwrite(STDERR, "src/vio_miniaudio_ns.h is stale - run php scripts/gen-miniaudio-namespace.php\n");
        exit(1);
    }
    echo "up to date (" . count($names) . " symbols, miniaudio {$ver['MAJOR']}.{$ver['MINOR']}.{$ver['REVISION']})\n";
    exit(0);
}

file_put_contents($out, $content);
echo "wrote src/vio_miniaudio_ns.h (" . count($names) . " symbols, miniaudio {$ver['MAJOR']}.{$ver['MINOR']}.{$ver['REVISION']})\n";
