{
    static const char *ext[] = { "VK_KHR_surface", "VK_KHR_wayland_surface" };
    *count = 2;
    return ext;
}

static int wl_vk_create_surface(vio_window_handle h, void *instance, void *out_surface)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (!w) return (int)VK_ERROR_INITIALIZATION_FAILED;
    VkWaylandSurfaceCreateInfoKHR ci;
    memset(&ci, 0, sizeof(ci));
    ci.sType = VK_STRUCTURE_TYPE_WAYLAND_SURFACE_CREATE_INFO_KHR;
    ci.display = wl.display;
    ci.surface = w->surface;
    return (int)vkCreateWaylandSurfaceKHR((VkInstance)instance, &ci, NULL, (VkSurfaceKHR *)out_surface);
}
#endif

static void wl_install_input(vio_window_handle h, vio_input_state *state)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (w) w->input = state;
}

