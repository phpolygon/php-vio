static void *wl_native_handle(vio_window_handle h, vio_native_kind kind)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (!w) return NULL;
    if (kind == VIO_NATIVE_WAYLAND_SURFACE) return w->surface;
    if (kind == VIO_NATIVE_WAYLAND_DISPLAY) return wl.display;
    return NULL;
}

