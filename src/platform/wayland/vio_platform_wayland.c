static void wl_registry_global(void *data, struct wl_registry *r, uint32_t id, const char *iface, uint32_t version)
{
    (void)data;
    if (strcmp(iface, wl_compositor_interface.name) == 0) {
        wl.compositor = wl_registry_bind(r, id, &wl_compositor_interface, version < 4 ? version : 4);
    } else if (strcmp(iface, wl_shm_interface.name) == 0) {
        wl.shm = wl_registry_bind(r, id, &wl_shm_interface, 1);
    } else if (strcmp(iface, xdg_wm_base_interface.name) == 0) {
        wl.wm_base = wl_registry_bind(r, id, &xdg_wm_base_interface, 1);
        xdg_wm_base_add_listener(wl.wm_base, &wl_wm_listener, NULL);
    } else if (strcmp(iface, wl_seat_interface.name) == 0 && !wl.seat) {
        wl.seat = wl_registry_bind(r, id, &wl_seat_interface, version < 5 ? version : 5);
        wl_seat_add_listener(wl.seat, &wl_seat_listener, NULL);
    } else if (strcmp(iface, wl_output_interface.name) == 0 && wl.output_n < WL_MAX_OUTPUTS) {
        wl_output_info *oi = &wl.outputs[wl.output_n++];
        memset(oi, 0, sizeof(*oi));
        oi->id = id;
        oi->scale = 1;
        oi->output = wl_registry_bind(r, id, &wl_output_interface, version < 2 ? version : 2);
        wl_output_add_listener(oi->output, &wl_output_listener, oi);
    } else if (strcmp(iface, zxdg_decoration_manager_v1_interface.name) == 0) {
        wl.decoration_manager = wl_registry_bind(r, id, &zxdg_decoration_manager_v1_interface, 1);
    } else if (strcmp(iface, zwp_relative_pointer_manager_v1_interface.name) == 0) {
        wl.relative_manager = wl_registry_bind(r, id, &zwp_relative_pointer_manager_v1_interface, 1);
    } else if (strcmp(iface, zwp_pointer_constraints_v1_interface.name) == 0) {
        wl.constraints = wl_registry_bind(r, id, &zwp_pointer_constraints_v1_interface, 1);
    }
}

static void wl_registry_remove(void *data, struct wl_registry *r, uint32_t id)
{
    (void)data; (void)r;
    for (int i = 0; i < wl.output_n; i++) {
        if (wl.outputs[i].id != id) continue;
        wl_output_destroy(wl.outputs[i].output);
        wl.outputs[i] = wl.outputs[--wl.output_n];
        break;
    }
}

static const struct wl_registry_listener wl_registry_listener = { wl_registry_global, wl_registry_remove };

/* ── Process lifecycle, events ────────────────────────────────────── */

static int wl_init(void)
{
    if (wl.initialized) return 1;
    wl.display = wl_display_connect(NULL);
    if (!wl.display) return 0;
    wl.xkb = xkb_context_new(XKB_CONTEXT_NO_FLAGS);
    wl.registry = wl_display_get_registry(wl.display);
    wl_registry_add_listener(wl.registry, &wl_registry_listener, NULL);
    wl_display_roundtrip(wl.display);   /* globals */
    wl_display_roundtrip(wl.display);   /* seat capabilities, output modes, keymap */
    if (!wl.compositor || !wl.wm_base) {
        php_error_docref(NULL, E_WARNING, "Wayland: the compositor offers no %s", wl.compositor ? "xdg_wm_base" : "wl_compositor");
        wl_display_disconnect(wl.display);
        memset(&wl, 0, sizeof(wl));
        return 0;
    }
    if (wl.shm) {
        const char *size = getenv("XCURSOR_SIZE");
        wl.cursor_theme = wl_cursor_theme_load(getenv("XCURSOR_THEME"), size && atoi(size) > 0 ? atoi(size) : 24, wl.shm);
        if (wl.cursor_theme) {
            wl.cursor = wl_cursor_theme_get_cursor(wl.cursor_theme, "left_ptr");
            if (!wl.cursor) wl.cursor = wl_cursor_theme_get_cursor(wl.cursor_theme, "default");
        }
        wl.cursor_surface = wl_compositor_create_surface(wl.compositor);
    }
    wl.initialized = 1;
    return 1;
}

static void wl_shutdown(void)
{
    if (!wl.initialized) return;
    if (wl.cursor_surface) wl_surface_destroy(wl.cursor_surface);
    if (wl.cursor_theme) wl_cursor_theme_destroy(wl.cursor_theme);
    if (wl.xkb_state) xkb_state_unref(wl.xkb_state);
    if (wl.keymap) xkb_keymap_unref(wl.keymap);
    if (wl.xkb) xkb_context_unref(wl.xkb);
    wl_display_flush(wl.display);
    wl_display_disconnect(wl.display);
    memset(&wl, 0, sizeof(wl));
    wl_egl_display = NULL;
}

/* Read what the compositor sent without blocking (timeout_ms 0), or wait. */
static void wl_dispatch(int timeout_ms)
{
    if (!wl.display) return;
    while (wl_display_prepare_read(wl.display) != 0) wl_display_dispatch_pending(wl.display);
    wl_display_flush(wl.display);
    struct pollfd pfd = { wl_display_get_fd(wl.display), POLLIN, 0 };
    if (poll(&pfd, 1, timeout_ms) > 0 && (pfd.revents & POLLIN)) wl_display_read_events(wl.display);
    else wl_display_cancel_read(wl.display);
    wl_display_dispatch_pending(wl.display);
}

static void wl_poll_events(void)
{
    wl_dispatch(0);
    wl_repeat_tick();
}

static void wl_wait_events(void)
{
    int timeout = -1;
    if (wl.repeat_key) {
        double ms = (wl.repeat_next - wl_now()) * 1000.0;
        timeout = ms > 0 ? (int)ms + 1 : 0;
    }
    wl_dispatch(timeout);
    wl_repeat_tick();
}

/* ── Window lifecycle ─────────────────────────────────────────────── */

static void wl_destroy_window(vio_window_handle h);

static vio_window_handle wl_create_window(vio_config *cfg, const char *backend_name)
{
    if (!wl_init()) {
        php_error_docref(NULL, E_WARNING, "Wayland: cannot connect to \"%s\"", getenv("WAYLAND_DISPLAY") ? getenv("WAYLAND_DISPLAY") : "");
        return NULL;
    }
    vio_wl_window *w = (vio_wl_window *)calloc(1, sizeof(vio_wl_window));
    if (!w) return NULL;
    w->headless = cfg->headless;
    w->decorated = !cfg->headless;
    w->monitor = -1;
    w->scale = 1;
    w->fb_w = w->fb_h = -1;
    w->width  = cfg->width  > 0 ? cfg->width  : 800;
    w->height = cfg->height > 0 ? cfg->height : 600;

    w->surface = wl_compositor_create_surface(wl.compositor);
    wl_surface_set_user_data(w->surface, w);
    wl_surface_add_listener(w->surface, &wl_surface_listener, w);
    w->xdg_surface = xdg_wm_base_get_xdg_surface(wl.wm_base, w->surface);
    xdg_surface_add_listener(w->xdg_surface, &wl_xdg_surface_listener, w);
    w->toplevel = xdg_surface_get_toplevel(w->xdg_surface);
    xdg_toplevel_add_listener(w->toplevel, &wl_toplevel_listener, w);
    xdg_toplevel_set_title(w->toplevel, cfg->title ? cfg->title : "php-vio");
    xdg_toplevel_set_app_id(w->toplevel, "php-vio");
    if (wl.decoration_manager) {
        w->decoration = zxdg_decoration_manager_v1_get_toplevel_decoration(wl.decoration_manager, w->toplevel);
        zxdg_toplevel_decoration_v1_add_listener(w->decoration, &wl_decoration_listener, w);
        zxdg_toplevel_decoration_v1_set_mode(w->decoration, w->decorated ? ZXDG_TOPLEVEL_DECORATION_V1_MODE_SERVER_SIDE
                                                                         : ZXDG_TOPLEVEL_DECORATION_V1_MODE_CLIENT_SIDE);
    }
    wl_surface_commit(w->surface);
    for (int i = 0; i < 20 && !w->configured; i++) wl_display_roundtrip(wl.display);
    if (!w->configured) {
        php_error_docref(NULL, E_WARNING, "Wayland: the compositor did not configure the window");
        wl_destroy_window(w);
        return NULL;
    }
    w->width  = cfg->width  > 0 ? cfg->width  : w->width;   /* the request wins over a first configure's size */
    w->height = cfg->height > 0 ? cfg->height : w->height;
    wl_apply_size(w);

    if (backend_name && strcmp(backend_name, "opengl") == 0) {
        int ok = wl_egl_load() && egl.BindAPI(WL_EGL_OPENGL_API);
        void *config = NULL;
        if (ok) {
            ok = 0;
            for (int ms = cfg->samples > 1 ? 1 : 0; ms >= 0 && !ok; ms--) {
                EGLint_ attrs[] = {
                    WL_EGL_SURFACE_TYPE, WL_EGL_WINDOW_BIT, WL_EGL_RENDERABLE_TYPE, WL_EGL_OPENGL_BIT,
                    WL_EGL_RED_SIZE, 8, WL_EGL_GREEN_SIZE, 8, WL_EGL_BLUE_SIZE, 8, WL_EGL_ALPHA_SIZE, 8,
                    WL_EGL_DEPTH_SIZE, 24, WL_EGL_STENCIL_SIZE, 8,
                    WL_EGL_SAMPLE_BUFFERS, ms, WL_EGL_SAMPLES, ms ? cfg->samples : 0,
                    WL_EGL_NONE
                };
                EGLint_ n = 0;
                ok = egl.ChooseConfig(wl_egl_display, attrs, &config, 1, &n) && n > 0;
            }
        }
        if (ok) {
            static const int ladder[][2] = { {4, 6}, {4, 5}, {4, 3}, {4, 1}, {3, 3}, {3, 2}, {3, 1}, {3, 0} };
            for (size_t i = 0; i < sizeof(ladder) / sizeof(ladder[0]) && !w->egl_context; i++) {
                int core = ladder[i][0] * 10 + ladder[i][1] >= 32;
                EGLint_ attrs[] = {
                    WL_EGL_CONTEXT_MAJOR, ladder[i][0], WL_EGL_CONTEXT_MINOR, ladder[i][1],
                    core ? WL_EGL_CONTEXT_PROFILE : WL_EGL_NONE, WL_EGL_CONTEXT_CORE_BIT, WL_EGL_NONE
                };
                w->egl_context = egl.CreateContext(wl_egl_display, config, NULL, attrs);
            }
            ok = w->egl_context != NULL;
        }
        if (ok) {
            w->egl_window = egl.window_create(w->surface, w->width * w->scale, w->height * w->scale);
            w->egl_surface = w->egl_window ? egl.CreateWindowSurface(wl_egl_display, config, w->egl_window, NULL) : NULL;
            ok = w->egl_surface && egl.MakeCurrent(wl_egl_display, w->egl_surface, w->egl_surface, w->egl_context);
        }
        if (ok) {
            /* the floor is 3.0, like GLFW's ladder */
            typedef const unsigned char *(*wl_glGetString_t)(unsigned int);
            wl_glGetString_t gs = (wl_glGetString_t)wl_gl_get_proc_address("glGetString");
            const char *ver = gs ? (const char *)gs(0x1F02) : NULL;
            ok = ver && atoi(ver) >= 3;
        }
        if (!ok) {
            php_error_docref(NULL, E_WARNING, "Wayland: no OpenGL context >= 3.0 available (EGL)");
            wl_destroy_window(w);
            return NULL;
        }
        /* a headless surface may be hidden: never wait for its frame callbacks */
        if (egl.SwapInterval) egl.SwapInterval(wl_egl_display, (cfg->vsync && !cfg->headless) ? 1 : 0);
    }
    wl_display_flush(wl.display);
    return w;
}

static void wl_destroy_window(vio_window_handle h)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (!w) return;
    if (wl.keyboard_focus == w) wl.keyboard_focus = NULL;
    if (wl.pointer_focus == w) wl.pointer_focus = NULL;
    if (w->egl_context) {
        if (egl.GetCurrentContext && egl.GetCurrentContext() == w->egl_context) egl.MakeCurrent(wl_egl_display, NULL, NULL, NULL);
        egl.DestroyContext(wl_egl_display, w->egl_context);
    }
    if (w->egl_surface) egl.DestroySurface(wl_egl_display, w->egl_surface);
    if (w->egl_window) egl.window_destroy(w->egl_window);
    if (w->relative) zwp_relative_pointer_v1_destroy(w->relative);
    if (w->locked) zwp_locked_pointer_v1_destroy(w->locked);
    if (w->decoration) zxdg_toplevel_decoration_v1_destroy(w->decoration);
    if (w->toplevel) xdg_toplevel_destroy(w->toplevel);
    if (w->xdg_surface) xdg_surface_destroy(w->xdg_surface);
    if (w->surface) wl_surface_destroy(w->surface);
    if (wl.display) wl_display_flush(wl.display);
    free(w);
}

