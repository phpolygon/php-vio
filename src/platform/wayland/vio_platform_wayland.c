/* ── Pointer ──────────────────────────────────────────────────────── */

static void wl_set_cursor(vio_wl_window *w)
{
    if (!wl.pointer) return;
    if (!w || w->cursor_mode != VIO_PLATFORM_CURSOR_NORMAL || !wl.cursor || !wl.cursor_surface) {
        wl_pointer_set_cursor(wl.pointer, wl.pointer_serial, NULL, 0, 0);
        return;
    }
    struct wl_cursor_image *img = wl.cursor->images[0];
    struct wl_buffer *buf = wl_cursor_image_get_buffer(img);
    if (!buf) return;
    wl_pointer_set_cursor(wl.pointer, wl.pointer_serial, wl.cursor_surface, (int32_t)img->hotspot_x, (int32_t)img->hotspot_y);
    wl_surface_attach(wl.cursor_surface, buf, 0, 0);
    wl_surface_damage(wl.cursor_surface, 0, 0, (int32_t)img->width, (int32_t)img->height);
    wl_surface_commit(wl.cursor_surface);
}

static void wl_pointer_enter(void *data, struct wl_pointer *p, uint32_t serial, struct wl_surface *s, wl_fixed_t sx, wl_fixed_t sy)
{
    (void)data; (void)p;
    wl.pointer_serial = serial;
    vio_wl_window *w = s ? (vio_wl_window *)wl_surface_get_user_data(s) : NULL;
    wl.pointer_focus = w;
    if (!w) return;
    wl_set_cursor(w);
    if (w->cursor_mode != VIO_PLATFORM_CURSOR_DISABLED) {
        w->cursor_x = wl_fixed_to_double(sx);
        w->cursor_y = wl_fixed_to_double(sy);
        vio_input_cursor_event(wl_input(w), w->cursor_x, w->cursor_y);
    }
}

static void wl_pointer_leave(void *data, struct wl_pointer *p, uint32_t serial, struct wl_surface *s)
{
    (void)data; (void)p; (void)serial; (void)s;
    wl.pointer_focus = NULL;
}

static void wl_pointer_motion(void *data, struct wl_pointer *p, uint32_t time, wl_fixed_t sx, wl_fixed_t sy)
{
    (void)data; (void)p; (void)time;
    vio_wl_window *w = wl.pointer_focus;
    if (!w || w->cursor_mode == VIO_PLATFORM_CURSOR_DISABLED) return;
    w->cursor_x = wl_fixed_to_double(sx);
    w->cursor_y = wl_fixed_to_double(sy);
    vio_input_cursor_event(wl_input(w), w->cursor_x, w->cursor_y);
}

static void wl_pointer_button(void *data, struct wl_pointer *p, uint32_t serial, uint32_t time, uint32_t button, uint32_t state)
{
    (void)data; (void)p; (void)time;
    wl.pointer_serial = serial;
    vio_wl_window *w = wl.pointer_focus;
    if (!w) return;
    int b = button == BTN_LEFT ? 0 : button == BTN_RIGHT ? 1 : button == BTN_MIDDLE ? 2 : (int)(button - BTN_SIDE) + 3;
    if (b < 0 || b > VIO_MOUSE_LAST) return;
    vio_input_button_event(wl_input(w), b, state == WL_POINTER_BUTTON_STATE_PRESSED ? VIO_PRESS : VIO_RELEASE);
}

/* GLFW's factor: one wheel notch (10 units) is 1.0, positive up / left. */
static void wl_pointer_axis(void *data, struct wl_pointer *p, uint32_t time, uint32_t axis, wl_fixed_t value)
{
    (void)data; (void)p; (void)time;
    vio_wl_window *w = wl.pointer_focus;
    if (!w) return;
    double v = -wl_fixed_to_double(value) / 10.0;
    if (axis == WL_POINTER_AXIS_VERTICAL_SCROLL) vio_input_scroll_event(wl_input(w), 0.0, v);
    else vio_input_scroll_event(wl_input(w), v, 0.0);
}

