/*
 * php-vio - Wayland platform (NATIVE-PLATFORM-PLAN Phase 3, OPEN-ITEMS A3)
 *
 * Linux on a Wayland compositor without GLFW or XWayland: xdg-shell
 * toplevels (server-side decorations through xdg-decoration where the
 * compositor offers them), keys by evdev keycode (the physical position, as
 * the Win32 scancodes and the X11 key names) with text, modifiers and the
 * compositor's repeat rate through xkbcommon, pointer buttons and wheels, a
 * locked pointer with relative motion for VIO_CURSOR_DISABLED, the cursor
 * theme's arrow through wayland-cursor, outputs as monitors (fullscreen on
 * an output - Wayland has no mode switch, the compositor scales), integer
 * buffer scale from the outputs the surface is on, evdev gamepads (shared
 * with X11), the Vulkan Wayland surface, and OpenGL through EGL on a
 * wl_egl_window - libEGL and libwayland-egl are opened at run time.
 *
 * The protocol glue for xdg-shell, xdg-decoration, relative-pointer and
 * pointer-constraints is generated by wayland-scanner at configure time
 * into gen/ (config.m4) and compiled into this translation unit.
 *
 * Chosen over X11 when WAYLAND_DISPLAY is set (src/vio_platform_registry.c),
 * as GLFW 3.4 does; VIO_PLATFORM=x11 picks XWayland instead. A Wayland
 * client cannot read or set its window position (always 0, 0), and a window
 * is only mapped once it has drawn - headless contexts are mapped too, or the
 * compositor would never send the frame callbacks a vsync'd present waits for.
 */

