static int wl_egl_load(void)
{
    if (wl_egl_display) return 1;
    if (!wl_libegl) wl_libegl = dlopen("libEGL.so.1", RTLD_LAZY | RTLD_GLOBAL);
    if (!wl_libwegl) wl_libwegl = dlopen("libwayland-egl.so.1", RTLD_LAZY | RTLD_GLOBAL);
    if (!wl_libegl || !wl_libwegl) return 0;
#define WL_EGL_SYM(field, name) *(void **)&egl.field = dlsym(wl_libegl, name)
    WL_EGL_SYM(GetDisplay, "eglGetDisplay");
    WL_EGL_SYM(Initialize, "eglInitialize");
    WL_EGL_SYM(BindAPI, "eglBindAPI");
    WL_EGL_SYM(ChooseConfig, "eglChooseConfig");
    WL_EGL_SYM(CreateContext, "eglCreateContext");
    WL_EGL_SYM(CreateWindowSurface, "eglCreateWindowSurface");
    WL_EGL_SYM(MakeCurrent, "eglMakeCurrent");
    WL_EGL_SYM(SwapBuffers, "eglSwapBuffers");
    WL_EGL_SYM(SwapInterval, "eglSwapInterval");
    WL_EGL_SYM(DestroySurface, "eglDestroySurface");
    WL_EGL_SYM(DestroyContext, "eglDestroyContext");
    WL_EGL_SYM(GetProcAddress, "eglGetProcAddress");
    WL_EGL_SYM(GetCurrentContext, "eglGetCurrentContext");
#undef WL_EGL_SYM
    egl.window_create  = (wl_egl_window_create_t)dlsym(wl_libwegl, "wl_egl_window_create");
    egl.window_resize  = (wl_egl_window_resize_t)dlsym(wl_libwegl, "wl_egl_window_resize");
    egl.window_destroy = (wl_egl_window_destroy_t)dlsym(wl_libwegl, "wl_egl_window_destroy");
    if (!egl.GetDisplay || !egl.Initialize || !egl.BindAPI || !egl.ChooseConfig || !egl.CreateContext
        || !egl.CreateWindowSurface || !egl.MakeCurrent || !egl.SwapBuffers || !egl.GetProcAddress
        || !egl.window_create || !egl.window_resize || !egl.window_destroy) return 0;
    void *d = egl.GetDisplay(wl.display);
    EGLint_ major = 0, minor = 0;
    if (!d || !egl.Initialize(d, &major, &minor)) return 0;
    wl_egl_display = d;
    return 1;
}

static void *wl_gl_get_proc_address(const char *name)
{
    void *p = (wl_egl_display && egl.GetProcAddress) ? egl.GetProcAddress(name) : NULL;
    if (p) return p;
    if (!wl_libgl) wl_libgl = dlopen("libOpenGL.so.0", RTLD_LAZY | RTLD_GLOBAL);
    if (!wl_libgl) wl_libgl = dlopen("libGL.so.1", RTLD_LAZY | RTLD_GLOBAL);
    return wl_libgl ? dlsym(wl_libgl, name) : NULL;
}

