/* ── Keyboard ─────────────────────────────────────────────────────── */

static void wl_keyboard_keymap(void *data, struct wl_keyboard *k, uint32_t format, int32_t fd, uint32_t size)
{
    (void)data; (void)k;
    if (format != WL_KEYBOARD_KEYMAP_FORMAT_XKB_V1) { close(fd); return; }
    char *map = mmap(NULL, size, PROT_READ, MAP_PRIVATE, fd, 0);
    close(fd);
    if (map == MAP_FAILED) return;
    struct xkb_keymap *km = xkb_keymap_new_from_string(wl.xkb, map, XKB_KEYMAP_FORMAT_TEXT_V1, XKB_KEYMAP_COMPILE_NO_FLAGS);
    munmap(map, size);
    if (!km) return;
    struct xkb_state *st = xkb_state_new(km);
    if (!st) { xkb_keymap_unref(km); return; }
    if (wl.xkb_state) xkb_state_unref(wl.xkb_state);
    if (wl.keymap) xkb_keymap_unref(wl.keymap);
    wl.keymap = km;
    wl.xkb_state = st;
}

static void wl_keyboard_enter(void *data, struct wl_keyboard *k, uint32_t serial, struct wl_surface *s, struct wl_array *keys)
{
    (void)data; (void)k; (void)serial; (void)keys;
    wl.keyboard_focus = s ? (vio_wl_window *)wl_surface_get_user_data(s) : NULL;
}

static void wl_keyboard_leave(void *data, struct wl_keyboard *k, uint32_t serial, struct wl_surface *s)
{
    (void)data; (void)k; (void)serial; (void)s;
    vio_wl_window *w = wl.keyboard_focus;
    wl.keyboard_focus = NULL;
    wl.repeat_key = 0;
    if (w && w->monitor >= 0 && w->auto_iconify) xdg_toplevel_set_minimized(w->toplevel);
}

static void wl_keyboard_key(void *data, struct wl_keyboard *k, uint32_t serial, uint32_t time, uint32_t key, uint32_t state)
{
    (void)data; (void)k; (void)serial; (void)time;
    vio_wl_window *w = wl.keyboard_focus;
    if (!w) return;
    int press = state == WL_KEYBOARD_KEY_STATE_PRESSED;
    wl_emit_key(w, key, press ? VIO_PRESS : VIO_RELEASE);
    if (press && wl.repeat_rate > 0 && wl.keymap && xkb_keymap_key_repeats(wl.keymap, key + 8)) {
        wl.repeat_key = key + 1;
        wl.repeat_next = wl_now() + wl.repeat_delay / 1000.0;
    } else if (!press && wl.repeat_key == key + 1) {
        wl.repeat_key = 0;
    }
}

static void wl_keyboard_modifiers(void *data, struct wl_keyboard *k, uint32_t serial, uint32_t dep, uint32_t lat, uint32_t lock, uint32_t group)
{
    (void)data; (void)k; (void)serial;
    if (wl.xkb_state) xkb_state_update_mask(wl.xkb_state, dep, lat, lock, 0, 0, group);
}

static void wl_keyboard_repeat_info(void *data, struct wl_keyboard *k, int32_t rate, int32_t delay)
{
    (void)data; (void)k;
    wl.repeat_rate = rate;
    wl.repeat_delay = delay;
}

static const struct wl_keyboard_listener wl_keyboard_listener = {
    wl_keyboard_keymap, wl_keyboard_enter, wl_keyboard_leave, wl_keyboard_key, wl_keyboard_modifiers, wl_keyboard_repeat_info,
};

/* Client-side key repeat at the compositor's rate. */
static void wl_repeat_tick(void)
{
    if (!wl.repeat_key || !wl.keyboard_focus || wl.repeat_rate <= 0) return;
    double now = wl_now();
    for (int n = 0; now >= wl.repeat_next && n < 64; n++) {
        wl_emit_key(wl.keyboard_focus, wl.repeat_key - 1, VIO_REPEAT);
        wl.repeat_next += 1.0 / wl.repeat_rate;
    }
}

