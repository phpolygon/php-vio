static int wl_gl_make_current(vio_window_handle h)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (!wl_egl_display) return -1;
    if (!w) return egl.MakeCurrent(wl_egl_display, NULL, NULL, NULL) ? 0 : -1;
    return egl.MakeCurrent(wl_egl_display, w->egl_surface, w->egl_surface, w->egl_context) ? 0 : -1;
}

static void wl_gl_swap_interval(int interval)
{
    if (wl_egl_display && egl.SwapInterval) egl.SwapInterval(wl_egl_display, interval);
}

/* ── Window properties ────────────────────────────────────────────── */

static void wl_set_title(vio_window_handle h, const char *utf8)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (w && utf8) { xdg_toplevel_set_title(w->toplevel, utf8); wl_display_flush(wl.display); }
}

/* Outside fullscreen / maximised the client picks its size. */
static void wl_set_window_size(vio_window_handle h, int ww, int wh)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (!w || w->monitor >= 0 || ww <= 0 || wh <= 0) return;
    w->width = ww;
    w->height = wh;
    wl_apply_size(w);
}

static void wl_get_window_pos(vio_window_handle h, int *x, int *y)
{
    (void)h;   /* Wayland clients cannot know their position */
    if (x) *x = 0;
    if (y) *y = 0;
}

static void wl_set_window_pos(vio_window_handle h, int x, int y) { (void)h; (void)x; (void)y; }

static int wl_get_attrib(vio_window_handle h, vio_window_attrib a)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (!w) return 0;
    switch (a) {
        case VIO_WINDOW_DECORATED:    return w->decorated;
        case VIO_WINDOW_MAXIMIZED:    return w->maximized;
        case VIO_WINDOW_AUTO_ICONIFY: return w->auto_iconify;
        case VIO_WINDOW_FOCUSED:      return wl.keyboard_focus == w;
        case VIO_WINDOW_VISIBLE:      return 1;
    }
    return 0;
}

static void wl_set_attrib(vio_window_handle h, vio_window_attrib a, int value)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (!w) return;
    switch (a) {
        case VIO_WINDOW_DECORATED:
            w->decorated = value ? 1 : 0;
            if (w->decoration) {
                zxdg_toplevel_decoration_v1_set_mode(w->decoration, w->decorated ? ZXDG_TOPLEVEL_DECORATION_V1_MODE_SERVER_SIDE
                                                                                 : ZXDG_TOPLEVEL_DECORATION_V1_MODE_CLIENT_SIDE);
            }
            break;
        case VIO_WINDOW_AUTO_ICONIFY:
            w->auto_iconify = value ? 1 : 0;
            break;
        default:
            break;
    }
    wl_display_flush(wl.display);
}

static void wl_maximize(vio_window_handle h)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (w) { xdg_toplevel_set_maximized(w->toplevel); wl_display_flush(wl.display); }
}

static void wl_restore(vio_window_handle h)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (w) { xdg_toplevel_unset_maximized(w->toplevel); wl_display_flush(wl.display); }
}

static void wl_set_cursor_mode(vio_window_handle h, int mode)
{
    vio_wl_window *w = (vio_wl_window *)h;
    if (!w || w->cursor_mode == mode) return;
    if (w->cursor_mode == VIO_PLATFORM_CURSOR_DISABLED) {
        if (w->locked) { zwp_locked_pointer_v1_destroy(w->locked); w->locked = NULL; }
        if (w->relative) { zwp_relative_pointer_v1_destroy(w->relative); w->relative = NULL; }
    }
    w->cursor_mode = mode;
    if (mode == VIO_PLATFORM_CURSOR_DISABLED && wl.pointer) {
        if (wl.constraints) {
            w->locked = zwp_pointer_constraints_v1_lock_pointer(wl.constraints, w->surface, wl.pointer, NULL,
                                                                ZWP_POINTER_CONSTRAINTS_V1_LIFETIME_PERSISTENT);
            zwp_locked_pointer_v1_add_listener(w->locked, &wl_locked_listener, w);
        }
        if (wl.relative_manager) {
            w->relative = zwp_relative_pointer_manager_v1_get_relative_pointer(wl.relative_manager, wl.pointer);
            zwp_relative_pointer_v1_add_listener(w->relative, &wl_relative_listener, w);
        }
    }
    if (wl.pointer_focus == w) wl_set_cursor(w);
    wl_display_flush(wl.display);
}

static int wl_window_monitor(vio_window_handle h)
{
    return h ? ((vio_wl_window *)h)->monitor : -1;
}

/* Fullscreen on an output: the compositor scales, there is no mode switch. */
static void wl_set_window_monitor(vio_window_handle h, int monitor, int x, int y, int width, int height, int refresh_hz)
{
    (void)x; (void)y; (void)refresh_hz;
    vio_wl_window *w = (vio_wl_window *)h;
    if (!w) return;
    if (monitor >= 0) {
        if (monitor >= wl.output_n) monitor = 0;
        w->monitor = monitor;
        xdg_toplevel_set_fullscreen(w->toplevel, wl.output_n ? wl.outputs[monitor].output : NULL);
    } else {
        w->monitor = -1;
        xdg_toplevel_unset_fullscreen(w->toplevel);
        if (width > 0 && height > 0) { w->width = width; w->height = height; }
    }
    wl_display_roundtrip(wl.display);
    wl_apply_size(w);
}

/* ── Monitors ─────────────────────────────────────────────────────── */

static int wl_monitor_count(void)
{
    return wl_init() ? wl.output_n : 0;
}

static int wl_primary_monitor(void)
{
    return wl_monitor_count() > 0 ? 0 : -1;   /* Wayland has no primary output: the first one */
}

static int wl_monitor_desc(int index, vio_monitor_desc *out)
{
    memset(out, 0, sizeof(*out));
    if (!wl_init() || index < 0 || index >= wl.output_n) return -1;
    wl_output_info *oi = &wl.outputs[index];
    const char *n = oi->name;
    while (*n == ' ') n++;
    snprintf(out->name, sizeof(out->name), "%s", *n ? n : "Wayland output");
    out->x = oi->x;
    out->y = oi->y;
    int s = oi->scale > 0 ? oi->scale : 1;
    out->work_x = oi->x;
    out->work_y = oi->y;
    out->work_width = oi->width / s;
    out->work_height = oi->height / s;
    out->scale_x = out->scale_y = (float)s;
    out->mode.width = oi->width;
    out->mode.height = oi->height;
    out->mode.refresh_hz = (oi->refresh_mhz + 500) / 1000;
    out->mode.red_bits = out->mode.green_bits = out->mode.blue_bits = 8;
    out->primary = index == 0;
    return 0;
}

static int wl_mode_cmp(const void *a, const void *b)
{
    const vio_video_mode *x = (const vio_video_mode *)a, *y = (const vio_video_mode *)b;
    long ax = (long)x->width * x->height, ay = (long)y->width * y->height;
    if (ax != ay) return ax < ay ? -1 : 1;
    if (x->width != y->width) return x->width - y->width;
    return x->refresh_hz - y->refresh_hz;
}

static int wl_video_modes(int index, vio_video_mode *out, int max)
{
    if (!wl_init() || index < 0 || index >= wl.output_n || max <= 0) return 0;
    wl_output_info *oi = &wl.outputs[index];
    int n = 0;
    for (int i = 0; i < oi->mode_n && n < max; i++) out[n++] = oi->modes[i];
    qsort(out, (size_t)n, sizeof(out[0]), wl_mode_cmp);
    return n;
}

